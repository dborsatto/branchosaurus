import Foundation
import PackageDescription

/// Where `cargo xtask swift-bindings` puts the Rust static library.
let rustLibraryDirectory = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent()  // apps/macos
    .deletingLastPathComponent()  // apps
    .deletingLastPathComponent()  // repository root
    .appendingPathComponent("target/macos/lib")
    .path

let package = Package(
    name: "Branchosaurus",
    // Keep in sync with MACOS_DEPLOYMENT_TARGET in xtask/src/main.rs.
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "Branchosaurus", targets: ["Branchosaurus"])
    ],
    targets: [
        // C declarations generated by UniFFI, plus the Rust library they link against.
        .target(
            name: "BranchosaurusFFI",
            path: "Sources/BranchosaurusFFI",
            linkerSettings: [
                .unsafeFlags(["-L", rustLibraryDirectory]),
                .linkedLibrary("branchosaurus_ffi"),
                .linkedLibrary("iconv"),
            ]
        ),
        // Swift bindings generated by UniFFI, and small extensions to them.
        .target(
            name: "BranchosaurusCore",
            dependencies: ["BranchosaurusFFI"],
            path: "Sources/BranchosaurusCore"
        ),
        .executableTarget(
            name: "Branchosaurus",
            dependencies: ["BranchosaurusCore"],
            path: "Sources/Branchosaurus"
        ),
        .testTarget(
            name: "BranchosaurusCoreTests",
            dependencies: ["BranchosaurusCore"],
            path: "Tests/BranchosaurusCoreTests"
        ),
    ]
)
